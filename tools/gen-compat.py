#!/usr/bin/env python3
"""Regenerate docs/COMPATIBILITY.md from the recipes. Run after editing recipes/.

    python3 tools/gen-compat.py           # write
    python3 tools/gen-compat.py --check   # CI: fail if stale
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from porthole import registry  # noqa: E402

TIERS = {
    1: ("Tier 1 — native ports",
        "An open-source reimplementation of the engine. Full speed, Metal rendering, "
        "touch controls designed rather than bolted on. The best possible outcome."),
    2: ("Tier 2 — emulated consoles",
        "A libretro core emulating the original hardware. Excellent for 8- and 16-bit; "
        "the later systems depend on JIT availability."),
    3: ("Tier 3 — interpreted runtimes",
        "The game was always data fed to an interpreter, and Porthole ships the "
        "interpreter. Reliable and frequently flawless."),
    4: ("Tier 4 — translation layer",
        "Research track. Arbitrary x86 Windows binaries via Wine and instruction "
        "translation. Expect disappointment."),
}

LEGEND = """| Status | Means |
|---|---|
| `supported` | built, run on a real iPhone, and played |
| `partial` | runs, with caveats recorded in the recipe |
| `experimental` | boots; may be unplayable |
| `planned` | recipe written, runtime not ported yet |
| `blocked` | can't proceed — see the recipe's notes |
"""


def main() -> int:
    recs = registry.recipes()
    rts = registry.runtimes()

    out = [
        "<!-- GENERATED by tools/gen-compat.py — edit recipes/, not this file. -->",
        "",
        "# Compatibility",
        "",
        f"{len(recs)} recipes. A *family* recipe covers a whole class of game rather "
        "than one title,",
        "so the real number of playable games is in the hundreds.",
        "",
        "Status is a promise to the next person, and contributors are asked not to "
        "inflate it:",
        "",
        LEGEND,
        "",
        "> **Everything is `planned` right now.** The build pipeline does not exist "
        "yet, so by the",
        "> definition above nothing can honestly claim more. Per-runtime iOS readiness "
        "is tracked",
        "> separately in [`runtimes/registry.toml`](../runtimes/registry.toml) as the "
        "`ios` field,",
        "> and `porthole plan <game>` reports it.",
        "",
    ]

    for tier in (1, 2, 3, 4):
        group = sorted(
            (r for r in recs.values() if r.tier == tier),
            key=lambda r: (r.is_family, r.title),
        )
        if not group:
            continue
        title, blurb = TIERS[tier]
        out += [f"## {title}", "", blurb, "",
                "| Game | Year | Runtime | Status | Controls |",
                "|---|---|---|---|---|"]
        for r in group:
            rt = rts.get(r.runtime, {})
            name = rt.get("name", r.runtime)
            year = r.year or "—"
            title_cell = f"**{r.title}**" + (" *(family)*" if r.is_family else "")
            out.append(
                f"| {title_cell} | {year} | {name} | `{r.status}` | `{r.layout}` |"
            )
        out.append("")

    out += [
        "## Missing a game?",
        "",
        "A recipe is about thirty lines of TOML and needs no Mac, no Xcode, and no "
        "Apple developer",
        "account — just a copy of the game and twenty minutes. "
        "See [RECIPES.md](RECIPES.md).",
        "",
        "Games whose engines have no open-source reimplementation and never ran on a "
        "console are",
        "Tier 4 territory, which is honestly not a good place. "
        "See [ROADMAP.md](ROADMAP.md#non-goals).",
        "",
    ]

    text = "\n".join(out)
    target = registry.repo_root() / "docs" / "COMPATIBILITY.md"

    if "--check" in sys.argv:
        current = target.read_text() if target.exists() else ""
        if current != text:
            print("COMPATIBILITY.md is stale — run: python3 tools/gen-compat.py")
            return 1
        print("COMPATIBILITY.md is up to date")
        return 0

    target.write_text(text)
    print(f"wrote {target.relative_to(registry.repo_root())} "
          f"({len(recs)} recipes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
