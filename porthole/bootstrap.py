"""Register an app id and obtain a provisioning profile.

Signing an iOS app needs a provisioning profile, and only Apple issues those. There
is no public API for it — the only supported path is Xcode's automatic signing, which
`xcodebuild -allowProvisioningUpdates` drives from the command line.

So this module generates a throwaway Xcode project whose sole purpose is to make
Xcode register the bundle id and fetch a profile, builds it once, and discards it.
The profile Xcode leaves behind in ~/Library/MobileDevice/Provisioning Profiles is
what `porthole sign` then finds on its own, including after Xcode renews it.

Generating a `.pbxproj` is the one place the no-Xcode-project rule bends. It bends
here rather than for the real build because this project is a stub -- one empty Swift
file -- so the generated file is small and does not have to track the real app's
sources, resources, or frameworks.

**This talks to Apple and changes the user's developer account.** A free Apple ID may
only register 10 app ids per 7 days, so it is never run implicitly: `porthole sign`
prints instructions and stops, and the user opts in by running `porthole bootstrap`.
"""

from __future__ import annotations

import plistlib
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from . import registry
from .build import IOS_MIN
from .sign import SignError, identities, profiles

# Deterministic object ids. Xcode only requires them to be unique within the file.
def _oid(n: int) -> str:
    return f"PH{n:022X}"


# Deliberately NOT main.swift: Swift treats a file by that name as top-level code,
# which cannot coexist with @UIApplicationMain ("attribute cannot be used in a module
# that contains top-level code").
STUB_FILENAME = "BootstrapDelegate.swift"

STUB_SWIFT = """\
// Generated by `porthole bootstrap`, for the sole purpose of making Xcode register
// an app id and fetch a provisioning profile. Not part of the real app, and deleted
// once the profile exists.
import UIKit

@UIApplicationMain
final class BootstrapDelegate: UIResponder, UIApplicationDelegate {}
"""


def _pbxproj(bundle_id: str, team_id: str, product: str) -> str:
    """A minimal iOS app project: one target, one Swift file, automatic signing.

    Note on the format: a .pbxproj is an old-style NeXT property list, so comments
    are `/* ... */` and never `#`. A stray `#` makes Xcode reject the whole file with
    "not a valid property list".

    SUPPORTED_PLATFORMS and SDKROOT are set on the target because without them
    xcodebuild warns that the scheme has no supported platforms and cannot resolve
    `-destination generic/platform=iOS`. The build succeeds regardless -- this was
    confirmed against a real account -- but the warning hides real errors.
    """
    o = {name: _oid(i) for i, name in enumerate([
        "project", "target", "product", "sourceFile", "sourceBuildFile",
        "mainGroup", "productsGroup", "sourcesPhase", "frameworksPhase",
        "resourcesPhase", "projectConfigList", "targetConfigList",
        "projectDebug", "targetDebug", "plistFile",
    ], start=1)}

    return f"""\
// !$*UTF8*$!
{{
	archiveVersion = 1;
	classes = {{}};
	objectVersion = 54;
	objects = {{

/* Begin PBXBuildFile section */
		{o['sourceBuildFile']} /* stub in Sources */ = {{isa = PBXBuildFile; fileRef = {o['sourceFile']} /* stub */; }};
/* End PBXBuildFile section */

/* Begin PBXFileReference section */
		{o['product']} /* {product}.app */ = {{isa = PBXFileReference; explicitFileType = wrapper.application; includeInIndex = 0; path = {product}.app; sourceTree = BUILT_PRODUCTS_DIR; }};
		{o['sourceFile']} /* stub */ = {{isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = {STUB_FILENAME}; sourceTree = "<group>"; }};
		{o['plistFile']} /* Info.plist */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.xml; path = Info.plist; sourceTree = "<group>"; }};
/* End PBXFileReference section */

/* Begin PBXFrameworksBuildPhase section */
		{o['frameworksPhase']} /* Frameworks */ = {{isa = PBXFrameworksBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0; }};
/* End PBXFrameworksBuildPhase section */

/* Begin PBXGroup section */
		{o['mainGroup']} = {{
			isa = PBXGroup;
			children = (
				{o['sourceFile']} /* stub */,
				{o['plistFile']} /* Info.plist */,
				{o['productsGroup']} /* Products */,
			);
			sourceTree = "<group>";
		}};
		{o['productsGroup']} /* Products */ = {{
			isa = PBXGroup;
			children = (
				{o['product']} /* {product}.app */,
			);
			name = Products;
			sourceTree = "<group>";
		}};
/* End PBXGroup section */

/* Begin PBXNativeTarget section */
		{o['target']} /* {product} */ = {{
			isa = PBXNativeTarget;
			buildConfigurationList = {o['targetConfigList']};
			buildPhases = (
				{o['sourcesPhase']} /* Sources */,
				{o['frameworksPhase']} /* Frameworks */,
				{o['resourcesPhase']} /* Resources */,
			);
			buildRules = ();
			dependencies = ();
			name = {product};
			productName = {product};
			productReference = {o['product']} /* {product}.app */;
			productType = "com.apple.product-type.application";
		}};
/* End PBXNativeTarget section */

/* Begin PBXProject section */
		{o['project']} /* Project object */ = {{
			isa = PBXProject;
			attributes = {{
				BuildIndependentTargetsInParallel = 1;
				LastSwiftUpdateCheck = 1600;
				LastUpgradeCheck = 1600;
				TargetAttributes = {{
					{o['target']} = {{
						CreatedOnToolsVersion = 16.0;
						DevelopmentTeam = {team_id};
						ProvisioningStyle = Automatic;
					}};
				}};
			}};
			buildConfigurationList = {o['projectConfigList']};
			compatibilityVersion = "Xcode 14.0";
			developmentRegion = en;
			hasScannedForEncodings = 0;
			knownRegions = (en, Base);
			mainGroup = {o['mainGroup']};
			productRefGroup = {o['productsGroup']} /* Products */;
			projectDirPath = "";
			projectRoot = "";
			targets = (
				{o['target']} /* {product} */,
			);
		}};
/* End PBXProject section */

/* Begin PBXResourcesBuildPhase section */
		{o['resourcesPhase']} /* Resources */ = {{isa = PBXResourcesBuildPhase; buildActionMask = 2147483647; files = (); runOnlyForDeploymentPostprocessing = 0; }};
/* End PBXResourcesBuildPhase section */

/* Begin PBXSourcesBuildPhase section */
		{o['sourcesPhase']} /* Sources */ = {{
			isa = PBXSourcesBuildPhase;
			buildActionMask = 2147483647;
			files = (
				{o['sourceBuildFile']} /* stub in Sources */,
			);
			runOnlyForDeploymentPostprocessing = 0;
		}};
/* End PBXSourcesBuildPhase section */

/* Begin XCBuildConfiguration section */
		{o['projectDebug']} /* Debug */ = {{
			isa = XCBuildConfiguration;
			buildSettings = {{
				ALWAYS_SEARCH_USER_PATHS = NO;
				CLANG_ENABLE_OBJC_ARC = YES;
				IPHONEOS_DEPLOYMENT_TARGET = {IOS_MIN};
				SDKROOT = iphoneos;
				SWIFT_VERSION = 5.0;
			}};
			name = Debug;
		}};
		{o['targetDebug']} /* Debug */ = {{
			isa = XCBuildConfiguration;
			buildSettings = {{
				CODE_SIGN_STYLE = Automatic;
				DEVELOPMENT_TEAM = {team_id};
				GENERATE_INFOPLIST_FILE = NO;
				INFOPLIST_FILE = Info.plist;
				PRODUCT_BUNDLE_IDENTIFIER = "{bundle_id}";
				PRODUCT_NAME = "$(TARGET_NAME)";
				SDKROOT = iphoneos;
				SUPPORTED_PLATFORMS = "iphoneos iphonesimulator";
				TARGETED_DEVICE_FAMILY = 1;
			}};
			name = Debug;
		}};
/* End XCBuildConfiguration section */

/* Begin XCConfigurationList section */
		{o['projectConfigList']} = {{
			isa = XCConfigurationList;
			buildConfigurations = (
				{o['projectDebug']} /* Debug */,
			);
			defaultConfigurationIsVisible = 0;
			defaultConfigurationName = Debug;
		}};
		{o['targetConfigList']} = {{
			isa = XCConfigurationList;
			buildConfigurations = (
				{o['targetDebug']} /* Debug */,
			);
			defaultConfigurationIsVisible = 0;
			defaultConfigurationName = Debug;
		}};
/* End XCConfigurationList section */
	}};
	rootObject = {o['project']} /* Project object */;
}}
"""


@dataclass
class BootstrapResult:
    bundle_id: str
    team_id: str
    profile_created: bool
    project_dir: Path
    log_tail: str


def team_ids() -> list[str]:
    """Team identifiers from the signing certificates in the keychain.

    Read from each certificate's OU field by `sign.identities()`. An earlier version
    parsed the parenthetical out of the common name, which for Apple Development
    certificates is the certificate id rather than the team -- a wrong value that
    looks right, and makes xcodebuild report "No Account for Team ...".
    """
    found: list[str] = []
    for identity in identities():
        if identity.team_id and identity.team_id not in found:
            found.append(identity.team_id)
    return found


def generate_project(bundle_id: str, team_id: str, where: Path,
                     product: str = "PortholeBootstrap") -> Path:
    """Write the throwaway project. Does not talk to Apple."""
    if where.exists():
        shutil.rmtree(where)
    where.mkdir(parents=True)

    (where / STUB_FILENAME).write_text(STUB_SWIFT)
    (where / "Info.plist").write_bytes(plistlib.dumps({
        "CFBundleExecutable": "$(EXECUTABLE_NAME)",
        "CFBundleIdentifier": "$(PRODUCT_BUNDLE_IDENTIFIER)",
        "CFBundleName": "$(PRODUCT_NAME)",
        "CFBundlePackageType": "APPL",
        "CFBundleShortVersionString": "1.0",
        "CFBundleVersion": "1",
        "UILaunchScreen": {},
    }))

    project = where / f"{product}.xcodeproj"
    project.mkdir()
    (project / "project.pbxproj").write_text(_pbxproj(bundle_id, team_id, product))
    return project


def validate_project(project: Path) -> list[str]:
    """Confirm Xcode can parse the generated project. Offline."""
    proc = subprocess.run(
        ["xcodebuild", "-list", "-project", str(project)],
        capture_output=True, text=True,
    )
    if proc.returncode != 0:
        raise SignError(
            "the generated Xcode project is malformed:\n"
            + (proc.stderr or proc.stdout).strip()
        )
    # xcodebuild -list prints "Targets:" then an indented list, followed by other
    # sections. Take only the target names.
    targets: list[str] = []
    in_targets = False
    for line in proc.stdout.splitlines():
        if line.strip() == "Targets:":
            in_targets = True
            continue
        if in_targets:
            if not line.startswith(" " * 8) or not line.strip():
                break
            targets.append(line.strip())
    return targets


def bootstrap(bundle_id: str, team_id: str | None = None,
              dry_run: bool = False) -> BootstrapResult:
    """Register the app id with Apple and fetch a profile.

    With `dry_run`, generates and validates the project but never contacts Apple.
    """
    teams = team_ids()
    if team_id is None:
        if not teams:
            raise SignError(
                "no signing certificate in your keychain, so there is no team to\n"
                "  register against.\n\n"
                "  Open Xcode, Settings -> Accounts, add your Apple ID, then\n"
                "  'Manage Certificates' -> + -> Apple Development.\n"
                "  A free Apple ID is enough."
            )
        team_id = teams[0]

    work = registry.repo_root() / ".cache" / "bootstrap"
    project = generate_project(bundle_id, team_id, work)
    targets = validate_project(project)

    if dry_run:
        return BootstrapResult(
            bundle_id=bundle_id, team_id=team_id, profile_created=False,
            project_dir=work,
            log_tail="dry run: project generated and parsed by xcodebuild, "
                     f"targets={targets}. Apple was not contacted.",
        )

    before = {p.path.name for p in profiles()}

    # The build itself is irrelevant; the signing phase is what registers the app id
    # and pulls down a profile. `generic/platform=iOS` avoids needing a device.
    proc = subprocess.run(
        [
            "xcodebuild", "-project", str(project),
            "-scheme", "PortholeBootstrap",
            "-destination", "generic/platform=iOS",
            "-allowProvisioningUpdates",
            f"DEVELOPMENT_TEAM={team_id}",
            "build",
        ],
        capture_output=True, text=True,
    )

    after = {p.path.name for p in profiles()}
    created = bool(after - before) or any(
        p.matches(bundle_id) for p in profiles()
    )

    output = proc.stderr or proc.stdout
    tail = "\n".join(output.strip().splitlines()[-25:])

    if not created:
        if "No Account for Team" in output:
            raise SignError(
                f"Xcode has no signed-in account for team {team_id}.\n\n"
                "  Your signing certificates are in the keychain, but Xcode itself is\n"
                "  not logged in, so it cannot ask Apple for a provisioning profile.\n\n"
                "  This step is interactive and cannot be scripted -- it needs an\n"
                "  Apple ID password and almost certainly a two-factor code:\n\n"
                "    1. Open Xcode\n"
                "    2. Settings -> Accounts -> + -> Apple ID\n"
                "    3. Sign in with the Apple ID that owns these certificates\n\n"
                "  Then run `porthole bootstrap` again.\n\n"
                f"  Last lines of xcodebuild:\n{tail}"
            )
        if "no profiles for" in output.lower() and "Account for Team" not in output:
            raise SignError(
                f"Xcode is signed in but would not issue a profile for '{bundle_id}'.\n\n"
                "  Most likely either a free account has hit its limit of 10 app ids\n"
                "  per 7 days, or this app id is already registered to another team.\n\n"
                f"  Last lines of xcodebuild:\n{tail}"
            )
        raise SignError(
            f"Xcode did not produce a profile for '{bundle_id}'.\n\n"
            f"  Last lines of xcodebuild:\n{tail}"
        )

    return BootstrapResult(
        bundle_id=bundle_id, team_id=team_id, profile_created=True,
        project_dir=work, log_tail=tail,
    )
